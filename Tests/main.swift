var passed = 0
func check(_ condition: @autoclosure () -> Bool, _ name: String) { if !condition() { fatalError("FAIL: \(name)") }; passed += 1 }
func near(_ a: Double, _ b: Double, _ name: String) { check(abs(a-b) < 0.00001, name) }
func calculate(_ kind: CalculationKind, _ overrides: [String:String] = [:]) throws -> CalculationResult {
    var v = Dictionary(uniqueKeysWithValues: kind.fields.map { ($0.id,$0.initial) }); v.merge(overrides) { _,b in b }; return try CalculationEngine.calculate(kind, values:v)
}
func invalid(_ kind: CalculationKind, _ values: [String:String], _ name: String) { do { _ = try calculate(kind, values); fatalError("Accepted invalid input: \(name)") } catch { passed += 1 } }
